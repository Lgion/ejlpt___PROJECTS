interface RawOfficialDrill {
  id: string;
  mode: ExerciseDrillMode;
  level: 'N5' | 'N4' | 'N3' | 'N2' | 'N1';
  prompt: string;
  targetWord?: string;
  reading?: string;
  expectedAnswers: string[];
  choices: string[];
  explanation: string;
  tags?: string[];
}

function makeDrill(raw: RawOfficialDrill): CollectionExerciseItem {
  const letters = ['a', 'b', 'c', 'd'];
  const options = raw.choices.map((text, idx) => ({
    id: letters[idx] || String(idx),
    text,
  }));
  const correctIdx = raw.choices.findIndex((c) => raw.expectedAnswers.includes(c));
  const correctOptionId = letters[correctIdx >= 0 ? correctIdx : 0];

  return {
    id: raw.id,
    fingerprint: computeExerciseFingerprint({
      mode: raw.mode,
      level: raw.level,
      prompt: raw.prompt,
      expectedAnswers: raw.expectedAnswers,
    }),
    source: 'official',
    mode: raw.mode,
    level: raw.level,
    prompt: raw.prompt,
    targetWord: raw.targetWord,
    reading: raw.reading,
    expectedAnswers: raw.expectedAnswers,
    options,
    correctOptionId,
    explanation: raw.explanation,
    tags: raw.tags,
    status: 'active',
    authorType: 'system',
    createdAt: '2026-11-26T00:00:00.000Z',
  };
}

